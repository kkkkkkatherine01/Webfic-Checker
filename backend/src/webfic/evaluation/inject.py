# --- base texts and their import ---------------------------------------------------------


@dataclass(frozen=True)
class Base:
    name: str  # "webnovelbench/017", "shushan", "private/势同水火"
    text: str


def bases(external: Path, private: Path) -> list[Base]:
    found = [
        Base(b.name, b.text)
        for b in webnovelbench_books(external / "webnovelbench" / "novel_data_subset_d_100.json")
    ]
    shushan = shushan_book(external / "shushan" / "shushan_001-012.txt")
    found.append(Base(shushan.name, shushan.text))
    for path in sorted((private / "published work").glob("*.txt")):
        found.append(Base(f"private/{path.stem}", path.read_text("utf-8-sig")))
    return found


def book_title(base: Base, version: str) -> str:
    """One book per text and extraction version (prompt, chunking): a new prompt gets
    fresh books, and the old ones stay for comparison."""
    digest = hashlib.sha256(base.text.encode()).hexdigest()[:10]
    return f"{base.name}#{digest}@{version[:8]}"


async def prepare(
    factory: Factory,
    make_llm: Callable[[uuid.UUID], LLMClient],
    settings: Settings,
    items: list[Base],
    *,
    concurrency: int = 6,
    on_progress: Callable[[str], None] = print,
) -> dict[str, uuid.UUID]:
    """Import, extract and check every base text once (an interrupted run resumes);
    returns name -> book id."""
    gate = asyncio.Semaphore(concurrency)
    books: dict[str, uuid.UUID] = {}
    version = extraction_version(load_prompt(), settings.chunk_size, settings.chunk_overlap)

    async def one(n: int, base: Base) -> None:
        async with gate:
            title = book_title(base, version)
            async with factory() as session:
                book_id = await session.scalar(
                    select(Book.id).where(Book.user_id == INJECT_USER, Book.title == title)
                )
                if book_id is None:
                    job = await imports.create_import_job(
                        session, user_id=INJECT_USER, title=title, text=base.text
                    )
                    book_id = job.book_id
            result = await imports.run_import_job(
                factory, make_llm(book_id), settings, user_id=INJECT_USER, book_id=book_id
            )
            async with factory() as session:
                await checks.run_checks(session, user_id=INJECT_USER, book_id=book_id)
            books[base.name] = book_id
            on_progress(
                f"[{n}/{len(items)}] {base.name}：抽取 {result.extracted} 章"
                f"（复用 {result.reused}，失败 {result.failed}），${result.cost_usd:.4f}"
            )

    await asyncio.gather(*(one(n, b) for n, b in enumerate(items, start=1)))
    return books


# --- what a prepared book holds -----------------------------------------------------------


@dataclass
class BookView:
    name: str
    book_id: uuid.UUID
    chapters: dict[int, str]  # number -> content
    names: dict[uuid.UUID, list[str]]  # character id -> canonical name, then aliases
    ages: list[AgeFact]
    elapsed: list[ElapsedFact]
    issues: list[IssueView]  # the open report on the original text

    def in_issue(self, fact: AgeFact) -> bool:
        return any(
            e.chapter_number == fact.chapter_number
            and e.char_start < fact.char_end
            and fact.char_start < e.char_end
            for issue in self.issues
            for e in issue.evidence
        )


async def load_view(session: AsyncSession, name: str, book_id: uuid.UUID) -> BookView:
    rows = await session.execute(
        select(Chapter.number, Chapter.content).where(
            Chapter.user_id == INJECT_USER, Chapter.book_id == book_id
        )
    )
    names: dict[uuid.UUID, list[str]] = {}
    for c in await session.scalars(
        select(Character).where(Character.user_id == INJECT_USER, Character.book_id == book_id)
    ):
        names[c.id] = [c.canonical_name]
    for a in await session.scalars(
        select(CharacterAlias).where(
            CharacterAlias.user_id == INJECT_USER, CharacterAlias.book_id == book_id
        )
    ):
        names.setdefault(a.character_id, []).append(a.alias)
    ages, elapsed = await _load_age_facts(session, INJECT_USER, book_id)
    report = await reports.get_report(session, user_id=INJECT_USER, book_id=book_id)
    return BookView(
        name, book_id, {n: c for n, c in rows.all()}, names, ages, elapsed, report.issues
    )


# --- numbers in the text's style -----------------------------------------------------------

_DIGITS = "零一二三四五六七八九"
_AGE_NUMBER = re.compile(r"[\d零〇一二两三四五六七八九十百]+(?=岁)")


def chinese(n: int) -> str:
    """1..999 in Chinese numerals as written in prose: 十七, 二十三, 一百零五."""
    if not 0 < n < 1000:
        raise ValueError(n)
    hundreds, rest = divmod(n, 100)
    tens, ones = divmod(rest, 10)
    out = f"{_DIGITS[hundreds]}百" if hundreds else ""
    if tens:
        out += ("" if tens == 1 and not hundreds else _DIGITS[tens]) + "十"
    elif hundreds and ones:
        out += "零"
    if ones:
        out += _DIGITS[ones]
    return out


def restyle(n: int, like: str) -> str:
    return str(n) if like.isdigit() else chinese(n)


# --- injections -------------------------------------------------------------------------


class Injection(BaseModel):
    id: str
    book: str
    kind: str
    character: str  # the name used (and, for modify, the character's canonical name)
    names: list[str]  # all the character's names, to recognise it after recomputing
    chapter: int  # the edited chapter
    old: str
    new: str
    span: tuple[int, int]  # the injected text in the edited chapter's new content
    ref: tuple[int, int, int] | None  # (chapter, start, end) of the age it is measured against
    expect: Confidence | None  # None: nothing may be reported
    distance: int  # chapters between ref and injection
    detail: str


def _pos(fact: AgeFact) -> tuple[int, int]:
    return (fact.chapter_number, fact.char_start)


def _gap(timeline: _Timeline, a: tuple[int, int], b: tuple[int, int]) -> float | None:
    """Story years between two positions, as the checker counts them."""
    between = timeline.between(a, b)
    if any(e.estimated_years is None for e in between):
        return None
    return sum(e.estimated_years or 0.0 for e in between)


def _exact_present(fact: AgeFact) -> bool:
    return (
        not fact.is_flashback
        and fact.value is not None
        and (fact.value_max is None or fact.value_max == fact.value)
    )


def _unique_window(content: str, start: int, end: int) -> tuple[int, int] | None:
    """Grow [start, end) until its text occurs once in the chapter."""
    for pad in range(0, 41, 5):
        lo, hi = max(0, start - pad), min(len(content), end + pad)
        if content.count(content[lo:hi]) == 1:
            return lo, hi
    return None


def _modify(view: BookView, a: AgeFact, b: AgeFact, kind: str, timeline: _Timeline):
    content = view.chapters[b.chapter_number]
    if content[b.char_start : b.char_end] != b.raw_text:
        return None
    tokens = [m for m in _AGE_NUMBER.finditer(b.raw_text) if parse_number(m.group()) == b.value]
    if len(tokens) != 1:
        return None
    assert a.value is not None and b.value is not None
    if kind == "modify_backwards":
        n = int(a.value) - 4
        expect = Confidence.CONFIRMED
    else:
        gap = _gap(timeline, _pos(a), _pos(b))
        if gap is None:
            return None
        n = round(a.value + gap) + 7
        expect = Confidence.SUSPECTED_REVIEW
    if n < 1 or n == b.value:
        return None
    token = tokens[0]
    new_raw = b.raw_text[: token.start()] + restyle(n, token.group()) + b.raw_text[token.end() :]
    window = _unique_window(content, b.char_start, b.char_end)
    if window is None:
        return None
    lo, hi = window
    old = content[lo:hi]
    new = content[lo : b.char_start] + new_raw + content[b.char_end : hi]
    return dict(
        chapter=b.chapter_number, old=old, new=new,
        span=(b.char_start, b.char_start + len(new_raw)), expect=expect,
        detail=f"前文 {a.value:g} 岁（第 {a.chapter_number} 章）；「{b.raw_text}」改成 {n} 岁",
    )  # fmt: skip


def _insertion_points(
    view: BookView,
    names: list[str],
    after: AgeFact,
    before: AgeFact | None,
    *,
    any_line: bool = False,
) -> list[tuple[int, int, str, str]]:
    """(chapter, line start, line, name) for lines mentioning the character (or, with
    `any_line`, any lines) after the line of one of its ages and before the next one."""
    usable = sorted({n for n in names if len(n) >= 2}, key=len, reverse=True)
    last = before.chapter_number if before else max(view.chapters)
    points = []
    for number in range(after.chapter_number, last + 1):
        content = view.chapters[number]
        start = 0
        for line in content.split("\n"):
            end = start + len(line)
            pos = (number, end)
            if (
                line.strip()
                and (number, start) >= (after.chapter_number, after.char_end)  # a later line
                and (before is None or pos < _pos(before))
                and content.count(line) == 1
            ):
                name = next((n for n in usable if n in line), names[0] if any_line else None)
                if name:
                    points.append((number, start, line, name))
            start = end + 1
    return points


def _insert(view: BookView, f: AgeFact, point, kind: str, timeline: _Timeline, rng: random.Random):
    number, start, line, name = point
    assert f.value is not None
    gap = _gap(timeline, _pos(f), (number, start + len(line)))
    expect = None
    if kind == "insert_backwards":
        n = int(f.value) - 4
        if n < 1:
            return None
        sentence, expect = f"{name}今年{chinese(n)}岁。", Confidence.CONFIRMED
        detail = f"前文 {f.value:g} 岁，插入 {n} 岁"
    elif gap is None:
        return None
    elif kind == "insert_jump":
        n = round(f.value + gap) + 7
        sentence, expect = f"{name}今年{chinese(n)}岁。", Confidence.SUSPECTED_REVIEW
        detail = f"前文 {f.value:g} 岁、期间 {gap:g} 年，插入 {n} 岁"
    elif kind == "control_consistent":
        projected = f.value + gap
        if abs(projected - round(projected)) > 0.3:
            return None
        n = round(projected)
        sentence = f"{name}今年{chinese(n)}岁了。"
        detail = f"前文 {f.value:g} 岁、期间 {gap:g} 年，插入 {n} 岁（一致）"
    elif kind == "control_flashback":
        k = rng.randint(3, 8)
        m = round(f.value + gap) - k
        if m < 2:
            return None
        sentence = f"{chinese(k)}年前，{name}才{chinese(m)}岁。"
        detail = f"推算现在 {round(f.value + gap)} 岁，插入 {k} 年前 {m} 岁（一致）"
    elif kind == "control_speculative":
        m = round(f.value + gap) + 15
        sentence = f"看样子，{name}大概有{chinese(m)}岁吧。"
        detail = f"推算 {round(f.value + gap)} 岁，插入猜测 {m} 岁"
    else:  # control_future, control_future_new
        k = rng.randint(3, 10)
        templates = FUTURE_TEMPLATES_NEW if kind == "control_future_new" else FUTURE_TEMPLATES
        sentence = rng.choice(templates).format(k=chinese(k), name=name)
        detail = f"两处年龄之间插入将来时长 {k} 年"
    return dict(
        chapter=number, old=line, new=line + sentence,
        span=(start + len(line), start + len(line) + len(sentence)), expect=expect,
        detail=detail, character=name,
    )  # fmt: skip


def candidates(view: BookView, kind: str, rng: random.Random) -> list[Injection]:
    """Every place in the book where an injection of `kind` can be made."""
    timeline = _Timeline(view.elapsed)
    found: list[Injection] = []
    by_character: dict[uuid.UUID, list[AgeFact]] = {}
    for fact in view.ages:
        # Thousand-year-old immortals are left out: injected numbers stay ordinary ages.
        usable = (
            fact.statement_type == "absolute_age"
            and not fact.speculative
            and fact.value is not None
            and 1 <= fact.value <= MAX_AGE
            and (fact.value_max is None or fact.value_max <= MAX_AGE)
        )
        if usable and _is_comparable(fact):
            by_character.setdefault(fact.character_id, []).append(fact)
    for character_id, facts in by_character.items():
        names = view.names.get(character_id, [])
        if not names:
            continue
        facts.sort(key=_pos)
        pairs = list(zip(facts, [*facts[1:], None], strict=True))
        for a, b in pairs:
            if not _exact_present(a) or view.in_issue(a):
                continue
            if b is not None and view.in_issue(b):
                continue
            made: list[dict] = []
            if kind.startswith("modify"):
                if b is not None and _exact_present(b):
                    one = _modify(view, a, b, kind, timeline)
                    if one:
                        made.append({**one, "character": names[0]})
            elif kind.startswith("control_future"):
                # Harmful only between two ages of the character, whatever the line says.
                points = _insertion_points(view, names, a, b, any_line=True) if b else []
                for point in rng.sample(points, min(FUTURE_PER_PAIR, len(points))):
                    made.append(_insert(view, a, point, kind, timeline, rng))
            else:
                points = _insertion_points(view, names, a, b)
                if points:
                    made.append(_insert(view, a, rng.choice(points), kind, timeline, rng))
            for one in filter(None, made):
                found.append(
                    Injection(
                        id=f"{view.name}/{kind}/{len(found)}",
                        book=view.name,
                        kind=kind,
                        names=names,
                        ref=(a.chapter_number, a.char_start, a.char_end),
                        distance=one["chapter"] - a.chapter_number,
                        **one,
                    )
                )
    return found


def plan(
    views: list[BookView],
    quotas: dict[str, int] = QUOTAS,
    seed: int = SEED,
    per_book: int = PER_BOOK,
) -> list[Injection]:
    """Spread each kind's quota over the books, at most `per_book` per book (more for
    the kinds in PER_BOOK_BY_KIND)."""
    rng = random.Random(seed)
    chosen: list[Injection] = []
    for kind, quota in quotas.items():
        pools = []
        for view in sorted(views, key=lambda v: v.name):
            pool = candidates(view, kind, rng)
            rng.shuffle(pool)
            if pool:
                pools.append(pool[: PER_BOOK_BY_KIND.get(kind, per_book)])
        rng.shuffle(pools)
        picked: list[Injection] = []
        for round_ in range(max((len(p) for p in pools), default=0)):
            for pool in pools:
                if len(picked) < quota and round_ < len(pool):
                    picked.append(pool[round_])
        chosen.extend(picked)
    return chosen


# --- running one injection ------------------------------------------------------------------


class Outcome(BaseModel):
    injection: Injection
    failed: bool = False
    detected: bool = False  # the expected pair reported
    confidence: Confidence | None = None
    involving: list[str] = []  # added issues touching the injected text
    collateral_added: list[str] = []  # other added issues
    removed: list[str] = []  # issues that disappeared
    age_on_span: list[str] = []  # how the injected age was extracted
    # right character, labelled as intended: present time (a flashback for
    # control_flashback), a guess only for control_speculative
    age_right: bool = False
    elapsed_on_span: list[str] = []  # kinds of time spans extracted from the injected text
    cost_usd: Decimal = Decimal(0)
    llm_calls: int = 0


def _touches(e, chapter: int, start: int, end: int) -> bool:
    return e.chapter_number == chapter and e.char_start < end and start < e.char_end


async def _subject_names(session: AsyncSession, subjects: list[str]) -> set[str]:
    ids = [uuid.UUID(s) for s in subjects]
    names = set(
        await session.scalars(select(Character.canonical_name).where(Character.id.in_(ids)))
    )
    names |= set(
        await session.scalars(
            select(CharacterAlias.alias).where(CharacterAlias.character_id.in_(ids))
        )
    )
    return names


async def run_injection(
    factory: Factory,
    llm: LLMClient,
    settings: Settings,
    book_id: uuid.UUID,
    inj: Injection,
) -> Outcome:
    out = Outcome(injection=inj)
    start, end = inj.span
    async with rolled_back(factory) as scoped:
        result = await chapters.patch_chapter(
            scoped, llm, settings, user_id=INJECT_USER, book_id=book_id,
            number=inj.chapter, old=inj.old, new=inj.new, dry_run=False,
        )  # fmt: skip
        out.failed = result.failed > 0
        out.cost_usd, out.llm_calls = result.cost_usd, result.llm_calls
        async with scoped() as session:
            for issue in result.issues_added:
                text = f"（{issue.confidence}）{issue.description}"
                if not any(_touches(e, inj.chapter, start, end) for e in issue.evidence):
                    out.collateral_added.append(text)
                    continue
                out.involving.append(text)
                right_character = bool(
                    await _subject_names(session, issue.subjects) & set(inj.names)
                )
                first, last = issue.evidence[0], issue.evidence[-1]
                if (
                    inj.expect is not None
                    and right_character
                    and inj.ref is not None
                    and _touches(first, *inj.ref)
                    and _touches(last, inj.chapter, start, end)
                    and not out.detected
                ):
                    out.detected, out.confidence = True, issue.confidence
            out.removed = [f"（{i.confidence}）{i.description}" for i in result.issues_removed]

            ages = await session.scalars(
                select(FactRow).where(
                    FactRow.user_id == INJECT_USER, FactRow.book_id == book_id,
                    FactRow.category == AGE.name, FactRow.chapter_number == inj.chapter,
                    FactRow.char_start < end, FactRow.char_end > start,
                )
            )  # fmt: skip
            for fact in ages:
                names = await _subject_names(session, [str(fact.character_id)])
                owner = (
                    "角色对" if names & set(inj.names) else f"角色错（{'、'.join(sorted(names))}）"
                )
                flags = [
                    x
                    for x, on in [("回忆", fact.is_flashback), ("推测", fact.is_speculative)]
                    if on
                ]
                value = "空" if fact.value_num is None else f"{fact.value_num:g}"
                out.age_on_span.append(
                    f"{fact.attribute} {value} {owner} {' '.join(flags)}".strip()
                )
                out.age_right = out.age_right or (
                    owner == "角色对"
                    and fact.attribute == "absolute_age"
                    and fact.is_speculative == (inj.kind == "control_speculative")
                    and fact.is_flashback == (inj.kind == "control_flashback")
                )
            spans = await session.scalars(
                select(ElapsedTimeFactRow).where(
                    ElapsedTimeFactRow.user_id == INJECT_USER,
                    ElapsedTimeFactRow.book_id == book_id,
                    ElapsedTimeFactRow.chapter_number == inj.chapter,
                    ElapsedTimeFactRow.char_start < end, ElapsedTimeFactRow.char_end > start,
                )
            )  # fmt: skip
            out.elapsed_on_span = [f"{e.kind} {e.estimated_years}" for e in spans]
    return out


async def run_all(
    factory: Factory,
    make_llm: Callable[[uuid.UUID], LLMClient],
    settings: Settings,
    books: dict[str, uuid.UUID],
    injections: list[Injection],
    *,
    concurrency: int = 6,
    on_done: Callable[[Outcome], None] | None = None,
) -> list[Outcome]:
    """Books run concurrently; the injections into one book one after another."""
    gate = asyncio.Semaphore(concurrency)
    by_book: dict[str, list[Injection]] = {}
    for inj in injections:
        by_book.setdefault(inj.book, []).append(inj)
    outcomes: list[Outcome] = []

    async def book(name: str, items: list[Injection]) -> None:
        async with gate:
            for inj in items:
                book_id = books[name]
                outcome = await run_injection(factory, make_llm(book_id), settings, book_id, inj)
                outcomes.append(outcome)
                if on_done:
                    on_done(outcome)

    await asyncio.gather(*(book(n, items) for n, items in by_book.items()))
    order = {inj.id: i for i, inj in enumerate(injections)}
    return sorted(outcomes, key=lambda o: order[o.injection.id])


# --- scoring ------------------------------------------------------------------------------


class KindMetrics(BaseModel):
    kind: str
    label: str
    n: int = 0
    failed: int = 0
    detected: Ratio = Ratio()  # detection kinds: the expected pair reported
    confidence_right: Ratio = Ratio()  # of detected
    false_alarm: Ratio = Ratio()  # controls: something reported on the injected text
    report_changed: Ratio = Ratio()  # anything added or removed at all
    collateral: Ratio = Ratio()  # issues added or removed that do not involve the injection
    age_extracted_right: Ratio = Ratio()  # injected age: right character and labels
    taken_as_advance: Ratio = Ratio()  # injected text extracted as story time passing
    misses: dict[str, int] = {}  # detection kinds: why the expected pair was not reported
    by_distance: dict[str, Ratio] = {}  # detection kinds: recall by chapters in between
    cost_usd: Decimal = Decimal(0)


def _miss_reason(o: Outcome) -> str:
    if o.failed:
        return "该章抽取失败"
    if not o.age_on_span:
        return "注入的年龄没抽到"
    if not o.age_right:
        return "抽到但归属 / 类型 / 回忆或推测标记不对"
    if o.involving:
        return "报出了，但两端或置信度不是预期的那一对"
    return "抽对了但检查器没报"


def _distance(d: int) -> str:
    return "同一章" if d == 0 else ("相隔 1–5 章" if d <= 5 else "相隔 6 章以上")


def score(outcomes: list[Outcome]) -> list[KindMetrics]:
    rows = []
    for kind, label in KINDS.items():
        items = [o for o in outcomes if o.injection.kind == kind]
        m = KindMetrics(kind=kind, label=label, n=len(items))
        misses: Counter[str] = Counter()
        distance: dict[str, Ratio] = {}
        for o in items:
            m.failed += o.failed
            m.cost_usd += o.cost_usd
            changed = bool(o.involving or o.collateral_added or o.removed)
            m.report_changed += Ratio(num=int(changed), den=1)
            m.collateral += Ratio(num=int(bool(o.collateral_added or o.removed)), den=1)
            m.taken_as_advance += Ratio(
                num=int(any(e.startswith("advance") for e in o.elapsed_on_span)), den=1
            )
            if not kind.startswith("control_future"):
                m.age_extracted_right += Ratio(num=int(o.age_right), den=1)
            if kind in DETECT:
                m.detected += Ratio(num=int(o.detected), den=1)
                if o.detected:
                    m.confidence_right += Ratio(num=int(o.confidence == o.injection.expect), den=1)
                else:
                    misses[_miss_reason(o)] += 1
                key = _distance(o.injection.distance)
                distance[key] = distance.get(key, Ratio()) + Ratio(num=int(o.detected), den=1)
            else:
                m.false_alarm += Ratio(num=int(bool(o.involving)), den=1)
        m.misses = dict(misses.most_common())
        m.by_distance = distance
        rows.append(m)
    return rows


