"""Error-injection evaluation (step 3.5-2).

Real novels are imported and extracted once for a dedicated evaluation user. Each
injection then edits one passage of one chapter as a dry run (the same path an author's
edit takes): only that chapter is read by the model again, the others reuse their stored
extraction, and the book is checked again. What the dry run adds to or removes from the
report is compared with what the injection should cause; everything is rolled back.

Kinds (all generated by code from the stored extraction, numbers in the text's style):
- modify_*: an existing present-time age is changed so it contradicts the one before it
- insert_*: "X今年N岁。" is added where X is mentioned, contradicting X's last age
- control_*: added sentences that must not be reported: an age that agrees, a flashback
  age that agrees, a guess that is far off, and a future / planned duration (which must
  not be taken as story time passing)
"""

